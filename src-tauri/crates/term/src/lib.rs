//! Real terminal sessions over PTY (`portable-pty`).
//!
//! `TerminalManager` opens up to [`MAX_SESSIONS`] interactive shells, each
//! in its own PTY with a dedicated reader thread (off the UI thread).
//! Output travels through [`EventSink`] in bounded chunks already
//! decoded to UTF-8 (multibyte sequences split across reads are
//! reassembled; invalid bytes are replaced, the flow never breaks).
//!
//! Security rules (see README):
//! - The child inherits the process environment **minus** the `META_*`
//!   family (including `META_API_KEY`). Nothing Ruth knows about
//!   inference crosses into the terminal. If the user shell loads its
//!   own credentials from their personal configuration, Ruth cannot
//!   prevent it and does not claim otherwise.
//! - The shell launches as a process with separate program and arguments;
//!   input is never concatenated into system commands.
//! - Identifiers (`term-N`, monotonic, never reused) are generated by
//!   Rust; the UI picks no commands or programs.
//! - Errors never include environment variables or content.
//!
//! The sink is a trait to avoid tying the manager to Tauri: the app uses
//! one that emits events and tests one that records.

use std::collections::HashMap;
use std::io::{Read, Write};
use std::path::PathBuf;
use std::sync::{Arc, Mutex};
use std::thread::JoinHandle;
use std::time::Duration;

use portable_pty::{native_pty_system, Child, CommandBuilder, MasterPty, PtySize};

/// Initial simultaneous sessions.
pub const MAX_SESSIONS: usize = 3;
/// Maximum read per emitted chunk (UTF-8 decoding may retain up to
/// 3 bytes of a split sequence).
pub const MAX_OUTPUT_CHUNK: usize = 8 * 1024;
/// Maximum payload accepted in one write (large pastes go in parts).
pub const MAX_WRITE_BYTES: usize = 256 * 1024;
/// Supported dimensions: columns 2–512, rows 1–256.
pub const MIN_COLS: u16 = 2;
pub const MAX_COLS: u16 = 512;
pub const MIN_ROWS: u16 = 1;
pub const MAX_ROWS: u16 = 256;

/// Environment prefix that never crosses to the child (covers `META_API_KEY`).
pub const SCRUB_PREFIX: &str = "META_";

/// Output and exit-notice destination. Everything runs on reader
/// threads, never on the UI thread.
pub trait EventSink: Send + Sync {
    fn output(&self, id: &str, data: &str);
    fn exited(&self, id: &str, code: Option<i32>);
}

/// How to launch the shell: separate program and arguments.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ShellSpec {
    pub program: String,
    pub args: Vec<String>,
}

impl ShellSpec {
    pub fn new(program: &str, args: &[&str]) -> Self {
        Self {
            program: program.to_string(),
            args: args.iter().map(|s| s.to_string()).collect(),
        }
    }

    /// Text to show in the UI (`/bin/bash`, `sh -i`, …).
    pub fn display(&self) -> String {
        if self.args.is_empty() {
            self.program.clone()
        } else {
            format!("{} {}", self.program, self.args.join(" "))
        }
    }
}

/// Default shell: `$SHELL` (program and arguments split on whitespace,
/// uninterpreted) or `/bin/sh`; on Windows PowerShell.
pub fn resolve_shell() -> ShellSpec {
    #[cfg(unix)]
    {
        if let Ok(from_env) = std::env::var("SHELL") {
            let mut parts = from_env.split_whitespace();
            if let Some(program) = parts.next() {
                return ShellSpec {
                    program: program.to_string(),
                    args: parts.map(str::to_string).collect(),
                };
            }
        }
        ShellSpec::new("/bin/sh", &[])
    }
    #[cfg(windows)]
    {
        ShellSpec::new("powershell.exe", &[])
    }
}

/// Removes the `META_*` family from the child environment (including
/// `META_API_KEY`). Pure and tested: the rest of the environment stays
/// intact so the user shell behaves like outside Ruth.
pub fn scrub_env(vars: &mut Vec<(String, String)>) {
    vars.retain(|(key, _)| !key.starts_with(SCRUB_PREFIX));
}

/// Child environment: the process one, scrubbed. Never logged.
pub fn child_env() -> Vec<(String, String)> {
    let mut vars: Vec<(String, String)> = std::env::vars().collect();
    scrub_env(&mut vars);
    vars
}

/// Initial folder when the person picks none: their `$HOME`
/// (`%USERPROFILE%` on Windows) or the current directory as fallback.
pub fn default_cwd() -> PathBuf {
    #[cfg(unix)]
    let home = std::env::var("HOME").ok().map(PathBuf::from);
    #[cfg(windows)]
    let home = std::env::var("USERPROFILE").ok().map(PathBuf::from);
    #[cfg(not(any(unix, windows)))]
    let home: Option<PathBuf> = None;
    home.filter(|dir| dir.is_dir())
        .or_else(|| std::env::current_dir().ok())
        .unwrap_or_else(|| PathBuf::from("."))
}

/// Decodes `chunk` added to the pending bytes and returns the ready
/// text, retaining in `pending` at most one incomplete sequence (< 4
/// bytes). Invalid bytes become the replacement character; the flow is never cut.
pub fn decode_incremental(pending: &mut Vec<u8>, chunk: &[u8]) -> String {
    pending.extend_from_slice(chunk);
    let mut text = String::new();
    loop {
        match std::str::from_utf8(pending) {
            Ok(valid) => {
                text.push_str(valid);
                pending.clear();
                return text;
            }
            Err(err) => {
                let up_to = err.valid_up_to();
                // SAFETY: `valid_up_to` delimits valid UTF-8.
                text.push_str(unsafe { std::str::from_utf8_unchecked(&pending[..up_to]) });
                match err.error_len() {
                    Some(len) => {
                        text.push('�');
                        pending.drain(..up_to + len);
                    }
                    None => {
                        pending.drain(..up_to);
                        return text;
                    }
                }
            }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TermErrorKind {
    TooManySessions,
    UnknownSession,
    SessionExited,
    SpawnFailed,
    BadSize,
    BadDirectory,
    PayloadTooLarge,
    Io,
}

/// Stable error: `kind` for the UI, secret-free English message.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TermError {
    pub kind: TermErrorKind,
    pub message: String,
}

impl TermError {
    fn new(kind: TermErrorKind, message: impl Into<String>) -> Self {
        Self {
            kind,
            message: message.into(),
        }
    }

    pub fn kind_str(&self) -> &'static str {
        match self.kind {
            TermErrorKind::TooManySessions => "too_many_sessions",
            TermErrorKind::UnknownSession => "unknown_session",
            TermErrorKind::SessionExited => "session_exited",
            TermErrorKind::SpawnFailed => "spawn_failed",
            TermErrorKind::BadSize => "bad_size",
            TermErrorKind::BadDirectory => "bad_directory",
            TermErrorKind::PayloadTooLarge => "payload_too_large",
            TermErrorKind::Io => "io_error",
        }
    }
}

impl std::fmt::Display for TermError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for TermError {}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum SessionStatus {
    Running,
    Exited { code: Option<i32> },
}

/// Public session card: folder, shell and state.
#[derive(Clone, Debug, serde::Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct SessionInfo {
    pub id: String,
    pub shell: String,
    pub cwd: String,
    pub cols: u16,
    pub rows: u16,
    pub running: bool,
    pub exit_code: Option<i32>,
}

struct Session {
    seq: u64,
    shell_display: String,
    cwd: String,
    cols: u16,
    rows: u16,
    master: Arc<Mutex<Box<dyn MasterPty + Send>>>,
    writer: Arc<Mutex<Box<dyn Write + Send>>>,
    child: Arc<Mutex<Box<dyn Child + Send + Sync>>>,
    status: Arc<Mutex<SessionStatus>>,
    reader: Option<JoinHandle<()>>,
}

impl Session {
    fn info(&self, id: &str) -> SessionInfo {
        let (running, exit_code) = match *self.status.lock().unwrap_or_else(|p| p.into_inner()) {
            SessionStatus::Running => (true, None),
            SessionStatus::Exited { code } => (false, code),
        };
        SessionInfo {
            id: id.to_string(),
            shell: self.shell_display.clone(),
            cwd: self.cwd.clone(),
            cols: self.cols,
            rows: self.rows,
            running,
            exit_code,
        }
    }
}

pub struct TerminalManager {
    sink: Arc<dyn EventSink>,
    next_seq: u64,
    sessions: HashMap<String, Session>,
}

impl TerminalManager {
    pub fn new(sink: Arc<dyn EventSink>) -> Self {
        Self {
            sink,
            next_seq: 1,
            sessions: HashMap::new(),
        }
    }

    /// Opens a session with the default shell and the scrubbed environment.
    /// The only path Tauri exposes: the UI picks no programs.
    pub fn create(
        &mut self,
        cwd: Option<PathBuf>,
        cols: u16,
        rows: u16,
    ) -> Result<SessionInfo, TermError> {
        let shell = resolve_shell();
        let env = child_env();
        self.create_with(&shell, &env, cwd, cols, rows)
    }

    /// Internal (and test) path with an explicit shell and environment.
    pub fn create_with(
        &mut self,
        shell: &ShellSpec,
        env: &[(String, String)],
        cwd: Option<PathBuf>,
        cols: u16,
        rows: u16,
    ) -> Result<SessionInfo, TermError> {
        if self.sessions.len() >= MAX_SESSIONS {
            return Err(TermError::new(
                TermErrorKind::TooManySessions,
                format!(
                    "There are already {MAX_SESSIONS} open terminals. Close one before opening another."
                ),
            ));
        }
        if !(MIN_COLS..=MAX_COLS).contains(&cols) || !(MIN_ROWS..=MAX_ROWS).contains(&rows) {
            return Err(TermError::new(
                TermErrorKind::BadSize,
                format!(
                    "Invalid size ({cols}×{rows}): columns {MIN_COLS}–{MAX_COLS}, rows {MIN_ROWS}–{MAX_ROWS}."
                ),
            ));
        }
        let base = cwd.unwrap_or_else(default_cwd);
        let canonical = base.canonicalize().map_err(|_| {
            TermError::new(
                TermErrorKind::BadDirectory,
                format!(
                    "Folder {} does not exist or is not accessible.",
                    base.display()
                ),
            )
        })?;
        if !canonical.is_dir() {
            return Err(TermError::new(
                TermErrorKind::BadDirectory,
                format!("Path {} is not a folder.", canonical.display()),
            ));
        }

        let id = format!("term-{}", self.next_seq);
        let seq = self.next_seq;
        self.next_seq += 1;

        let pty_system = native_pty_system();
        let size = PtySize {
            rows,
            cols,
            pixel_width: 0,
            pixel_height: 0,
        };
        let pair = pty_system.openpty(size).map_err(|err| {
            TermError::new(
                TermErrorKind::SpawnFailed,
                format!("Could not open the terminal: {err}."),
            )
        })?;
        let mut cmd = CommandBuilder::new(&shell.program);
        cmd.args(shell.args.iter().map(String::as_str));
        cmd.cwd(&canonical);
        cmd.env_clear();
        for (key, value) in env {
            cmd.env(key, value);
        }
        let child = pair.slave.spawn_command(cmd).map_err(|err| {
            TermError::new(
                TermErrorKind::SpawnFailed,
                format!("Could not start {}: {err}.", shell.program),
            )
        })?;
        drop(pair.slave);
        let reader = pair.master.try_clone_reader().map_err(|err| {
            TermError::new(
                TermErrorKind::SpawnFailed,
                format!("Could not read the terminal: {err}."),
            )
        })?;

        let writer = pair.master.take_writer().map_err(|err| {
            TermError::new(
                TermErrorKind::SpawnFailed,
                format!("Could not write to the terminal: {err}."),
            )
        })?;
        let master = Arc::new(Mutex::new(pair.master));
        let writer = Arc::new(Mutex::new(writer));
        let child = Arc::new(Mutex::new(child));
        let status = Arc::new(Mutex::new(SessionStatus::Running));
        let handle = spawn_reader(
            id.clone(),
            reader,
            Arc::clone(&child),
            Arc::clone(&status),
            Arc::clone(&self.sink),
        );
        let session = Session {
            seq,
            shell_display: shell.display(),
            cwd: canonical.to_string_lossy().to_string(),
            cols,
            rows,
            master,
            writer,
            child,
            status,
            reader: Some(handle),
        };
        let info = session.info(&id);
        self.sessions.insert(id, session);
        Ok(info)
    }

    fn get(&self, id: &str) -> Result<&Session, TermError> {
        self.sessions.get(id).ok_or_else(|| {
            TermError::new(
                TermErrorKind::UnknownSession,
                format!("Session {id} does not exist (it may have closed already)."),
            )
        })
    }

    /// A session card (folder, shell, size, state).
    pub fn describe(&self, id: &str) -> Result<SessionInfo, TermError> {
        Ok(self.get(id)?.info(id))
    }

    /// Sessions in creation order.
    pub fn list(&self) -> Vec<SessionInfo> {
        let mut entries: Vec<(&String, &Session)> = self.sessions.iter().collect();
        entries.sort_by_key(|(_, session)| session.seq);
        entries
            .iter()
            .map(|(id, session)| session.info(id))
            .collect()
    }

    pub fn running_count(&self) -> usize {
        self.sessions
            .values()
            .filter(|session| {
                matches!(
                    *session.status.lock().unwrap_or_else(|p| p.into_inner()),
                    SessionStatus::Running
                )
            })
            .count()
    }

    fn check_running(session: &Session, id: &str) -> Result<(), TermError> {
        match *session.status.lock().unwrap_or_else(|p| p.into_inner()) {
            SessionStatus::Running => Ok(()),
            SessionStatus::Exited { code } => Err(TermError::new(
                TermErrorKind::SessionExited,
                match code {
                    Some(code) => format!("Session {id} already ended (code {code})."),
                    None => format!("Session {id} already ended."),
                },
            )),
        }
    }

    /// Writes keys to the session (Ctrl+C, arrows and escapes travel
    /// verbatim: the PTY program interprets them, not Ruth).
    pub fn write(&self, id: &str, data: &str) -> Result<(), TermError> {
        let session = self.get(id)?;
        Self::check_running(session, id)?;
        if data.len() > MAX_WRITE_BYTES {
            return Err(TermError::new(
                TermErrorKind::PayloadTooLarge,
                format!(
                    "Payload too large ({} bytes, at most {} KiB). Paste it in parts.",
                    data.len(),
                    MAX_WRITE_BYTES / 1024
                ),
            ));
        }
        let mut writer = session.writer.lock().unwrap_or_else(|p| p.into_inner());
        writer.write_all(data.as_bytes()).map_err(|err| {
            TermError::new(
                TermErrorKind::Io,
                format!("Could not write to session {id}: {err}."),
            )
        })
    }

    /// Resizes the PTY (rows/columns); the program receives `SIGWINCH`.
    pub fn resize(&mut self, id: &str, cols: u16, rows: u16) -> Result<SessionInfo, TermError> {
        if !(MIN_COLS..=MAX_COLS).contains(&cols) || !(MIN_ROWS..=MAX_ROWS).contains(&rows) {
            return Err(TermError::new(
                TermErrorKind::BadSize,
                format!(
                    "Invalid size ({cols}×{rows}): columns {MIN_COLS}–{MAX_COLS}, rows {MIN_ROWS}–{MAX_ROWS}."
                ),
            ));
        }
        let session = self.get(id)?;
        Self::check_running(session, id)?;
        {
            let master = session.master.lock().unwrap_or_else(|p| p.into_inner());
            master
                .resize(PtySize {
                    rows,
                    cols,
                    pixel_width: 0,
                    pixel_height: 0,
                })
                .map_err(|err| {
                    TermError::new(
                        TermErrorKind::Io,
                        format!("Could not resize session {id}: {err}."),
                    )
                })?;
        }
        let session = self.sessions.get_mut(id).expect("session checked");
        session.cols = cols;
        session.rows = rows;
        Ok(session.info(id))
    }

    /// Closes the session: kills the child, awaits its end, joins the
    /// reader thread and releases the PTY. No orphans on the happy path.
    pub fn close(&mut self, id: &str) -> Result<(), TermError> {
        let mut session = self.sessions.remove(id).ok_or_else(|| {
            TermError::new(
                TermErrorKind::UnknownSession,
                format!("Session {id} does not exist (it may have closed already)."),
            )
        })?;
        kill_and_reap(&session.child);
        if let Some(handle) = session.reader.take() {
            let _ = handle.join();
        }
        Ok(())
    }

    /// Closes everything (app exit): kills each child before releasing.
    pub fn shutdown(&mut self) {
        let ids: Vec<String> = self.sessions.keys().cloned().collect();
        for id in ids {
            let _ = self.close(&id);
        }
    }
}

/// Kills the child and awaits its end (up to ~1 s); best effort per
/// platform, without blocking forever.
fn kill_and_reap(child: &Arc<Mutex<Box<dyn Child + Send + Sync>>>) {
    let mut guard = child.lock().unwrap_or_else(|p| p.into_inner());
    let _ = guard.kill();
    for _ in 0..100 {
        match guard.try_wait() {
            Ok(Some(_)) => return,
            Ok(None) => std::thread::sleep(Duration::from_millis(10)),
            Err(_) => return,
        }
    }
}

/// Reader thread: reads until EOF, emits decoded chunks and at the end
/// awaits the child, marks the state and emits the exit notice.
fn spawn_reader(
    id: String,
    mut reader: Box<dyn Read + Send>,
    child: Arc<Mutex<Box<dyn Child + Send + Sync>>>,
    status: Arc<Mutex<SessionStatus>>,
    sink: Arc<dyn EventSink>,
) -> JoinHandle<()> {
    std::thread::Builder::new()
        .name(format!("ruth-term-{id}"))
        .spawn(move || {
            let mut pending: Vec<u8> = Vec::new();
            let mut buf = [0u8; MAX_OUTPUT_CHUNK];
            loop {
                match reader.read(&mut buf) {
                    Ok(0) => break,
                    Ok(n) => {
                        let text = decode_incremental(&mut pending, &buf[..n]);
                        if !text.is_empty() {
                            sink.output(&id, &text);
                        }
                    }
                    Err(err) if err.kind() == std::io::ErrorKind::Interrupted => continue,
                    Err(_) => break,
                }
            }
            if !pending.is_empty() {
                sink.output(&id, &String::from_utf8_lossy(&pending));
            }
            let code = child
                .lock()
                .unwrap_or_else(|p| p.into_inner())
                .wait()
                .ok()
                .map(|exit| exit.exit_code() as i32);
            *status.lock().unwrap_or_else(|p| p.into_inner()) = SessionStatus::Exited { code };
            sink.exited(&id, code);
        })
        .expect("could not launch the terminal reader thread")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scrub_removes_meta_and_keeps_the_rest() {
        let mut vars = vec![
            ("META_API_KEY".to_string(), "secret".to_string()),
            ("META_FOO".to_string(), "x".to_string()),
            ("PATH".to_string(), "/bin".to_string()),
            ("HOME".to_string(), "/home/u".to_string()),
        ];
        scrub_env(&mut vars);
        assert_eq!(
            vars,
            vec![
                ("PATH".to_string(), "/bin".to_string()),
                ("HOME".to_string(), "/home/u".to_string()),
            ]
        );
    }

    #[test]
    fn decode_reassembles_split_multibyte() {
        let mut pending = Vec::new();
        let emoji = "áé".as_bytes();
        let first = decode_incremental(&mut pending, &emoji[..1]);
        assert_eq!(first, "");
        assert!(!pending.is_empty());
        let rest = decode_incremental(&mut pending, &emoji[1..]);
        assert_eq!(rest, "áé");
        assert!(pending.is_empty());
    }

    #[test]
    fn decode_replaces_invalid_without_cutting() {
        let mut pending = Vec::new();
        let text = decode_incremental(&mut pending, b"ok\xff\xfemal");
        assert_eq!(text, "ok��mal");
        assert!(pending.is_empty());
    }
}
